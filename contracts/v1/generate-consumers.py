"""Generate wire types from canonical schemas. Run after changing JSON schemas."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent
schemas = {p.name: json.loads(p.read_text()) for p in (ROOT / 'schemas').glob('*.json')}
roots = {'appointment-lookup.schema.json':'AppointmentLookupResult','confirmation.schema.json':'CallerConfirmation','profile-capability.schema.json':'ProfileCapabilityRevision','receipt.schema.json':'OperationReceipt','session-terminal.schema.json':'TerminalSession'}
def pascal(value): return ''.join(word[:1].upper()+word[1:] for word in value.replace('_','-').split('-'))
names = {(file, ''): name for file,name in roots.items()}
for file,schema in schemas.items():
 for key in schema.get('$defs', {}): names[file,'#/$defs/'+key] = {'state':'WorkflowState','event':'WorkflowEvent'}.get(key,pascal(key)) if file=='workflow.schema.json' else pascal(key)
def target(reference,file):
 parts=reference.split('#'); f=parts[0].split('/')[-1] or file
 return names[f,'#'+parts[1] if len(parts)>1 else '']
py_defs=[]
def render(s,file,name,lang):
 if '$ref' in s:
  t=target(s['$ref'],file); return json.dumps(t) if lang=='py' else t
 if 'const' in s or 'enum' in s:
  values=[s['const']] if 'const' in s else s['enum']
  vals=[repr(x) if lang=='py' else json.dumps(x) for x in values]
  return 'Literal['+', '.join(vals)+']' if lang=='py' else ' | '.join(vals)
 variants=s.get('oneOf',s.get('anyOf'))
 # Object constraints plus anyOf required contact methods retain the base fields in types.
 if variants and 'properties' not in s:
  vals=[render(v,file,name+str(i),lang) for i,v in enumerate(variants)]
  return 'Union['+', '.join(vals)+']' if lang=='py' else '('+' | '.join(vals)+')'
 typ=s.get('type')
 if isinstance(typ,list):
  vals=[render({'type':t},file,name,lang) for t in typ]
  return 'Union['+', '.join(vals)+']' if lang=='py' else ' | '.join(vals)
 if typ=='object':
  if 'properties' not in s:
   v=render(s.get('additionalProperties',{}),file,name+'Value',lang)
   return f'Dict[str, {v}]' if lang=='py' else f'{{ [key: string]: {v} }}'
  props=[]
  for key,value in s['properties'].items():
   t=render(value,file,name+pascal(key),lang); optional=key not in s.get('required',[])
   props.append(f'{key!r}: '+(f'NotRequired[{t}]' if optional else t) if lang=='py' else f'{key if key.isidentifier() else json.dumps(key)}{"?" if optional else ""}: {t}')
  if lang=='py':
   py_defs.append(f'{name} = TypedDict({name!r}, {{'+', '.join(props)+'})')
   return json.dumps(name)
  return '{ '+'; '.join(props)+' }'
 if typ=='array':
  t=render(s['items'],file,name+'Item',lang);return f'List[{t}]' if lang=='py' else f'Array<{t}>'
 return ({'string':'str','integer':'int','number':'float','boolean':'bool','null':'None'}.get(typ,'Any') if lang=='py' else {'string':'string','integer':'number','number':'number','boolean':'boolean','null':'null'}.get(typ,'unknown'))
ts=['// Generated by generate-consumers.py. JSON schemas are canonical.']
for (file,fragment),name in names.items():
 s=schemas[file] if not fragment else schemas[file]['$defs'][fragment.rsplit('/',1)[1]]
 ts.append(f'export type {name} = {render(s,file,name,"ts")};')
 rendered=render(s,file,name,'py')
 if rendered != json.dumps(name): py_defs.append(f'{name} = {rendered}')
workflows=json.loads((ROOT/'workflows.json').read_text())
ts.append('export const DEADLINES_SECONDS = '+json.dumps(workflows['deadlinesSeconds'])+' as const;')
ts.append('export const WORKFLOW_IDS: readonly WorkflowId[] = '+json.dumps([w['id'] for w in workflows['workflows']])+';')
ts.append('''
// Input must be current server-loaded records, never worker-provided authority.
export function confirmationAuthorizesWrite(binding: CallerConfirmation, current: ConfirmationState): boolean {
 return binding.dialogueAct === 'affirm' && current.latestCallerDialogueAct === 'affirm' && current.latestCallerClassificationStatus === 'classified'
  && binding.workflowInstanceId === current.workflowInstanceId && binding.callerTurnId === current.latestCallerTurnId
  && binding.callerTurnSequence === current.latestCallerTurnSequence && binding.callerTurnSequence > current.readbackAfterCallerTurnSequence
  && binding.fieldRevision === current.fieldRevision && binding.readbackRevision === current.readbackRevision && binding.readbackPayloadHash === current.readbackPayloadHash;
}
export function mayMutateSession(session: SessionGuard): boolean {
 return session?.status === 'active' && ['interpreting','collecting','clarifying','reading_back','awaiting_confirmation','operating','completed'].includes(session.phase);
}
''')
(ROOT/'typescript/index.ts').write_text('\n'.join(ts).rstrip()+'\n')
(ROOT/'python/wire_types.py').write_text('"""Generated wire types; use validate_contract at runtime trust boundaries."""\nfrom typing import Any, Dict, List, Literal, Union, TypedDict, NotRequired\n\n'+'\n'.join(py_defs)+'\n')
